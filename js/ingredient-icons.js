/**
 * 获取食材对应的 Emoji 图标
 * @param {string} name 食材名称
 * @param {string} category 食材分类（可选）
 * @returns {string} Emoji 图标
 */
function getIngredientIcon(name, category) {
  if (!name) return '📦';
  // 精确匹配
  if (IngredientIcons[name]) return IngredientIcons[name];
  // 前缀匹配（如"鸡胸肉"匹配"鸡"）
  const keys = Object.keys(IngredientIcons).filter(k => k !== '_defaults');
  for (const key of keys) {
    if (name.includes(key) || key.includes(name)) {
      return IngredientIcons[key];
    }
  }
  // 按分类匹配
  if (category && IngredientIcons._defaults[category]) {
    return IngredientIcons._defaults[category];
  }
  // 分类匹配改良版
  if (category === '蔬菜' || category === '蔬菜类') return '🥬';
  if (category === '肉类' || category === '肉') return '🥩';
  if (category === '海鲜') return '🦐';
  if (category === '水果') return '🍎';
  if (category === '饮料') return '🥤';
  if (category === '调料' || category === '调味料') return '🧂';
  if (category === '冷冻食品' || category === '冷冻') return '❄️';
  if (category === '零食') return '🍪';
  if (category.match(/蛋|奶|乳/) || category === '蛋奶' || category === '乳制品') return '🥚';
  if (category.match(/豆|豆腐/) || category === '豆制品') return '🟫';
  if (category.match(/主食|米|面|粮/) || category === '主食') return '🍚';
  // 如果没有分类，尝试从名称推断
  if (name.includes('鸡')) return '🍗';
  if (name.includes('牛')) return '🥩';
  if (name.includes('猪')) return '🥩';
  if (name.includes('羊')) return '🍖';
  if (name.includes('鱼')) return '🐟';
  if (name.includes('虾')) return '🦐';
  if (name.includes('蛋')) return '🥚';
  if (name.includes('豆腐')) return '🟫';
  if (name.includes('奶') || name.includes('牛乳')) return '🥛';
  return '📦';
}

window.IngredientIcons = IngredientIcons;
window.getIngredientIcon = getIngredientIcon;